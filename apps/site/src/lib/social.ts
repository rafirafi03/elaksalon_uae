/** Detects the platform from a URL. Unknown hosts get a generic globe icon; invalid URLs are skipped. */
export function detectSocial(url: string): { url: string; platform: SocialPlatform } | null {
  let host: string;
  try {
    const parsed = new URL(url.trim());
    if (parsed.protocol !== "https:" && parsed.protocol !== "http:") return null;
    host = parsed.hostname.toLowerCase().replace(/^www\./, "");
  } catch {
    return null;
  }
  const platform =
    SOCIAL_PLATFORMS.find((p) => p.hosts.some((h) => host === h || host.endsWith(`.${h}`))) ?? WEBSITE;
  return { url: url.trim(), platform };
}
